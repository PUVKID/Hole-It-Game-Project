    private static Material MakeMat(string key, string shaderName, Color color)
    {
        Shader sh = Shader.Find(shaderName);
        if (sh == null) throw new System.InvalidOperationException("Required shader missing: "+shaderName);
        Material m = new Material(sh);
        if (m.HasProperty("_Color")) m.SetColor("_Color", color);
        if (m.HasProperty("_Glossiness")) m.SetFloat("_Glossiness", 0.28f);
        if (m.HasProperty("_Metallic")) m.SetFloat("_Metallic", 0.02f);
        return SaveAsset(m, MatDir + "/" + key + ".mat");
    }

    private static Dictionary<string, Material> CreateMaterials(Texture2D soft)
    {
        Dictionary<string, Material> d = new Dictionary<string, Material>();
        d["Ground"] = MakeMat("Ground", "HoleIt/GroundStencil", Color.white);
        // Saturated violet checkerboard inspired by colourful casual puzzle arenas.
        if (d["Ground"].HasProperty("_ColorA")) d["Ground"].SetColor("_ColorA", new Color(0.43f, 0.15f, 0.72f, 1f));
        if (d["Ground"].HasProperty("_ColorB")) d["Ground"].SetColor("_ColorB", new Color(0.38f, 0.12f, 0.66f, 1f));
        if (d["Ground"].HasProperty("_Tiles")) d["Ground"].SetFloat("_Tiles", 30f);
        d["Mask"] = MakeMat("HoleMask", "HoleIt/HoleMask", Color.white);
        d["Pit"] = MakeMat("HolePit", "HoleIt/HolePit", Color.white);
        d["Rim"] = MakeMat("HoleRim", "HoleIt/HoleRim", Color.white);
        d["Rim"].SetColor("_Color", new Color(0.88f, 0.97f, 1f, 0.96f));
        EditorUtility.SetDirty(d["Ground"]);
        d["Dark"] = MakeMat("Dark", "Mobile/Diffuse", new Color(0.18f, 0.18f, 0.22f));
        Material p = MakeMat("Particle", "Mobile/Particles/Additive", Color.white);
        if (soft != null) p.SetTexture("_MainTex", soft);
        d["Particle"] = p;
        EditorUtility.SetDirty(d["Rim"]);
        EditorUtility.SetDirty(p);
        return d;
    }

    private static Material ColorMat(Dictionary<string, Material> mats, string key, Color c)
    {
        string k = "Mat_" + key;
        if (!mats.ContainsKey(k)) mats[k] = MakeMat(k, Shader.Find("Standard") != null ? "Standard" : "Mobile/Diffuse", c);
        return mats[k];
    }


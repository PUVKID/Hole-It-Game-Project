    private static Dictionary<string,EdibleData> CreateEdibles(Dictionary<string,Material> mats)
    {
        var result=new Dictionary<string,EdibleData>();
        foreach(Spec spec in AllSpecs()) {
            string path=EdibleDir+"/Edible_"+spec.key+".asset";
            EdibleData data=AssetDatabase.LoadAssetAtPath<EdibleData>(path);
            bool fresh=data==null;
            if(fresh) {
                data=ScriptableObject.CreateInstance<EdibleData>();data.objectId=spec.key;data.displayName=spec.display;
                data.objectType=spec.type;data.sizeTier=spec.tier;data.score=spec.score;data.growthValue=spec.growth;
                data.canBeSwallowed=true;data.uiColor=spec.color;data.specialTimeBonus=spec.type==ObjectType.TimeBoost?8:0;
                data.colorVariant=spec.key=="CarS"?ColorVariant.Red:spec.key=="CarBlue"?ColorVariant.Blue:spec.key=="CarYellow"?ColorVariant.Yellow:ColorVariant.None;
                data=SaveAsset(data,path);
            }
            if(data.prefab==null) {
                GameObject baked=AssetDatabase.LoadAssetAtPath<GameObject>(PrefabDir+"/Edible_"+spec.key+".prefab");
                if(baked!=null)data.prefab=baked;
                else {
                    Mesh mesh=AssetDatabase.LoadAssetAtPath<Mesh>(MeshDir+"/Completed_"+spec.key+".asset");
                    if(mesh!=null) {
                        HoleItProjectValidation.CheckMesh(mesh);
                        GameObject go=new GameObject("Edible_"+spec.key);
                        try {
                            go.layer=LayerMask.NameToLayer(Layers.EdibleName);go.AddComponent<MeshFilter>().sharedMesh=mesh;
                            var mr=go.AddComponent<MeshRenderer>();mr.sharedMaterial=AssetDatabase.LoadAssetAtPath<Material>(MatDir+"/VertexLit.mat");
                            var body=go.AddComponent<Rigidbody>();body.isKinematic=true;body.useGravity=false;
                            var col=go.AddComponent<BoxCollider>();col.center=mesh.bounds.center;col.size=mesh.bounds.size;
                            var edible=go.AddComponent<EdibleObject>();SetRef(edible,"data",data);
                            data.footprintRadius=new Vector2(mesh.bounds.extents.x,mesh.bounds.extents.z).magnitude;
                            data.prefab=PrefabUtility.SaveAsPrefabAsset(go,PrefabDir+"/Edible_"+spec.key+".prefab");
                        } finally {Object.DestroyImmediate(go);}
                    } else {
                        data.prefab=BuildDetailedEdiblePrefab(spec,data,mats);
                        NormalisePrefab(data,spec);
                    }
                }
            }
            if(fresh && data.footprintRadius<=0.5f) {
                var col=data.prefab.GetComponent<BoxCollider>();
                if(col!=null)data.footprintRadius=new Vector2(col.size.x,col.size.z).magnitude*.5f*data.prefab.transform.localScale.x;
            }
            if(data.icon==null) {
                data.icon=AssetDatabase.LoadAssetAtPath<Sprite>(TexDir+"/Icon_"+spec.key+".png");
                if(data.icon==null)data.icon=RenderOwnIcon(data.prefab,spec.key);
            }
            EditorUtility.SetDirty(data);result.Add(spec.key,data);
        }
        return result;
    }
    private static void NormalisePrefab(EdibleData data,Spec spec) {
        string path=AssetDatabase.GetAssetPath(data.prefab);GameObject root=PrefabUtility.LoadPrefabContents(path);
        try {
            Bounds bounds=new Bounds();bool first=true;
            foreach(var r in root.GetComponentsInChildren<Renderer>()) {if(first){bounds=r.bounds;first=false;}else bounds.Encapsulate(r.bounds);}
            float radius=new Vector2(bounds.extents.x,bounds.extents.z).magnitude;
            float[] caps={.70f,1.05f,1.40f,1.83f,2.37f,2.99f};float scale=Mathf.Min(1,caps[Mathf.Clamp(spec.tier-1,0,5)]/Mathf.Max(.01f,radius));
            if(root.transform.localScale!=Vector3.one)throw new System.InvalidOperationException("Generated model root must have identity scale before normalization.");
            for(int childIndex=0;childIndex<root.transform.childCount;childIndex++) {
                Transform child=root.transform.GetChild(childIndex);child.localPosition*=scale;child.localScale*=scale;
            }
            var box=root.GetComponent<BoxCollider>();if(box!=null){box.center*=scale;box.size*=scale;}
            var sphere=root.GetComponent<SphereCollider>();if(sphere!=null){sphere.center*=scale;sphere.radius*=scale;}
            var capsule=root.GetComponent<CapsuleCollider>();if(capsule!=null){capsule.center*=scale;capsule.radius*=scale;capsule.height*=scale;}
            data.footprintRadius=radius*scale;
            PrefabUtility.SaveAsPrefabAsset(root,path);
        } finally {PrefabUtility.UnloadPrefabContents(root);}
    }

    private static LevelData[] CreateLevels(Dictionary<string,EdibleData> edibles) {
        string path=DataDir+"/CampaignRecipe.json";
        if(!File.Exists(path))throw new System.IO.FileNotFoundException("Authored campaign recipe is missing",path);
        var recipe=JsonUtility.FromJson<CampaignFile>(File.ReadAllText(path));
        if(recipe==null||recipe.levels==null||recipe.levels.Length!=30)throw new System.InvalidOperationException("CampaignRecipe must contain 30 levels");
        var levels=new LevelData[30];
        for(int i=0;i<levels.Length;i++) {
            RecipeLevel r=recipe.levels[i];string assetPath=LevelDir+"/Level_"+r.id.ToString("00")+".asset";
            LevelData existing=AssetDatabase.LoadAssetAtPath<LevelData>(assetPath);
            // A normal rebuild preserves Inspector tuning; explicit Reset Campaign is a separate action.
            if(existing!=null){levels[i]=existing;continue;}
            LevelData l=ScriptableObject.CreateInstance<LevelData>();l.schemaVersion=8;l.levelId=r.id;l.levelTitle=r.title;l.difficulty=Mathf.Clamp((r.id+5)/6,1,5);
            l.timeLimit=r.time;l.theme=AssetDatabase.LoadAssetAtPath<ThemeData>(DataDir+"/Themes/"+r.theme+".asset");
            if(l.theme==null)throw new System.InvalidOperationException("Missing theme "+r.theme+"; restore the six authored ThemeData assets from the delivered archive.");
            l.arenaSize=new Vector2(r.size[0],r.size[1]);l.gridSize=new Vector2Int(r.grid[0],r.grid[1]);l.holeStart=new Vector2(r.start[0],r.start[1]);l.startClearRadius=r.clearRadius;
            l.growthMultiplier=r.growth;l.randomSeed=r.seed;l.defaultWrongBehavior=(WrongTargetBehavior)r.rule;l.nextLevelId=r.id<30?r.id+1:0;l.movementSpeed=8;
            l.missions=new MissionData[r.missions.Length];
            for(int m=0;m<l.missions.Length;m++){var rm=r.missions[m];var d=edibles[rm.key];l.missions[m]=new MissionData{missionId="L"+r.id.ToString("00")+"_M"+(m+1),kind=(MissionKind)rm.kind,target=d,category=d.objectType,color=d.colorVariant,tier=d.sizeTier,requiredCount=rm.count,icon=d.icon,description=d.displayName};}
            l.spawnGroups=new SpawnGroup[r.groups.Length];for(int g=0;g<l.spawnGroups.Length;g++){var rg=r.groups[g];l.spawnGroups[g]=new SpawnGroup{edible=edibles[rg.key],count=rg.count,center=new Vector2(rg.center[0],rg.center[1]),radius=rg.radius,ring=rg.ring};}
            l.placements=new SpawnPlacement[r.placements.Length];for(int p=0;p<l.placements.Length;p++){var rp=r.placements[p];l.placements[p]=new SpawnPlacement{edible=edibles[rp.key],position=new Vector2(rp.position[0],rp.position[1]),yaw=rp.yaw,decorative=rp.decorative};}
            levels[i]=SaveAsset(l,assetPath);
        }
        return levels;
    }

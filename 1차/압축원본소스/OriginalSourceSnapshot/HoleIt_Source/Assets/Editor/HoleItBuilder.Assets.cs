    /// <summary>d = 중심 0 ~ 가장자리 1 의 거리. alpha 함수로 흰색 PNG를 만든다.</summary>
    private static Sprite MakeSprite(string name, int size, System.Func<float, float> alphaByDist, bool sprite)
    {
        string path = TexDir + "/" + name + ".png";
        Texture2D t = new Texture2D(size, size, TextureFormat.RGBA32, false);
        Color[] px = new Color[size * size];
        for (int y = 0; y < size; y++)
        {
            for (int x = 0; x < size; x++)
            {
                float dx = (x + 0.5f) / size - 0.5f;
                float dy = (y + 0.5f) / size - 0.5f;
                float d = Mathf.Sqrt(dx * dx + dy * dy) * 2f;
                px[y * size + x] = new Color(1f, 1f, 1f, Mathf.Clamp01(alphaByDist(d)));
            }
        }
        t.SetPixels(px);
        t.Apply();
        File.WriteAllBytes(Path.Combine(Directory.GetCurrentDirectory(), path), t.EncodeToPNG());
        Object.DestroyImmediate(t);
        AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);

        TextureImporter imp = AssetImporter.GetAtPath(path) as TextureImporter;
        if (imp != null)
        {
            imp.textureType = sprite ? TextureImporterType.Sprite : TextureImporterType.Default;
            imp.alphaIsTransparency = true;
            imp.mipmapEnabled = false;
            imp.SaveAndReimport();
        }
        return AssetDatabase.LoadAssetAtPath<Sprite>(path);
    }

    /// <summary>Rounded rectangle texture with a vertical colour gradient and a nine-slice border.</summary>
    private static Sprite MakeRoundedGradientSprite(string name, int size, Color top, Color bottom)
    {
        string path = TexDir + "/" + name + ".png";
        Texture2D t = new Texture2D(size, size, TextureFormat.RGBA32, false);
        Color[] px = new Color[size * size];
        const float cornerRadius = 0.19f;
        for (int y = 0; y < size; y++)
        {
            float ny = (y + 0.5f) / size;
            Color gradient = Color.Lerp(bottom, top, ny);
            for (int x = 0; x < size; x++)
            {
                float nx = (x + 0.5f) / size;
                float qx = Mathf.Abs(nx - 0.5f) - (0.5f - cornerRadius);
                float qy = Mathf.Abs(ny - 0.5f) - (0.5f - cornerRadius);
                float ox = Mathf.Max(qx, 0f);
                float oy = Mathf.Max(qy, 0f);
                float sd = Mathf.Sqrt(ox * ox + oy * oy) + Mathf.Min(Mathf.Max(qx, qy), 0f) - cornerRadius;
                float alpha = Mathf.Clamp01(0.5f - sd * size);
                px[y * size + x] = new Color(gradient.r, gradient.g, gradient.b, alpha * gradient.a);
            }
        }
        t.SetPixels(px);
        t.Apply();
        File.WriteAllBytes(Path.Combine(Directory.GetCurrentDirectory(), path), t.EncodeToPNG());
        Object.DestroyImmediate(t);
        AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
        TextureImporter imp = AssetImporter.GetAtPath(path) as TextureImporter;
        if (imp != null)
        {
            imp.textureType = TextureImporterType.Sprite;
            imp.spriteImportMode = SpriteImportMode.Single;
            imp.alphaIsTransparency = true;
            imp.mipmapEnabled = false;
            imp.textureCompression = TextureImporterCompression.Uncompressed;
            imp.spritePixelsPerUnit = 100f;
            imp.spriteBorder = new Vector4(24f, 24f, 24f, 24f);
            // Unity 6 exposes spriteMeshType through TextureImporterSettings,
            // not directly on TextureImporter.
            TextureImporterSettings spriteSettings = new TextureImporterSettings();
            imp.ReadTextureSettings(spriteSettings);
            spriteSettings.spriteMeshType = SpriteMeshType.FullRect;
            imp.SetTextureSettings(spriteSettings);
            imp.SaveAndReimport();
        }
        return AssetDatabase.LoadAssetAtPath<Sprite>(path);
    }


    private static Dictionary<string, EdibleData> CreateEdibles(Dictionary<string, Material> mats)
    {
        Dictionary<string, EdibleData> result = new Dictionary<string, EdibleData>();
        List<Spec> specs = AllSpecs();
        for (int i = 0; i < specs.Count; i++)
        {
            Spec sp = specs[i];

            EdibleData data = ScriptableObject.CreateInstance<EdibleData>();
            data.displayName = sp.display;
            data.uiColor = sp.color;
            data.objectType = sp.type;
            data.sizeTier = sp.tier;
            data.score = sp.score;
            data.growthValue = sp.growth;
            // Hole it! 처럼 미션 대상이 아니어도 크기만 맞으면 전부 먹을 수 있게 한다.
            // (예전에는 가로등/벤치/콘 등 소품이 canBeSwallowed=false, 점수/성장 0 이라 절대 먹히지 않았다)
            data.canBeSwallowed = true;
            if (sp.type != ObjectType.TimeBoost && sp.score <= 0)
            {
                data.score = 4 + sp.tier * 4;
                data.growthValue = 0.35f + sp.tier * 0.15f;
            }
            data = SaveAsset(data, EdibleDir + "/Edible_" + sp.key + ".asset");

            GameObject prefab = BuildDetailedEdiblePrefab(sp, data, mats);
            data.prefab = prefab;
            EditorUtility.SetDirty(data);
            result[sp.key] = data;
        }
        return result;
    }


        l.levelTitle = title;
        l.difficulty = diff;
        l.timeLimit = time;
        l.mapSize = map;
        l.initialSizeTier = tier;
        l.growthMultiplier = growthMul;
        l.cameraZoomMultiplier = cam;
        l.missions = missions;
        l.spawnGroups = groups.ToArray();
        l.randomSeed = seed;
        l.defaultWrongBehavior = WrongTargetBehavior.None;   // 미션 대상이 아니어도 먹을 수 있음 (점수/성장만, 미션 카운트는 대상만)

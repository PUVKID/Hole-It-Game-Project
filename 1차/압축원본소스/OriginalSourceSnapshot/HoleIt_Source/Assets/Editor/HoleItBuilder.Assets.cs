    /// <summary>두 점 사이에 n개를 일렬로 배치 (벽/줄 배치용).</summary>
    private static void Line(List<SpawnGroup> list, string key, float x1, float z1, float x2, float z2, int n)
    {
        for (int i = 0; i < n; i++)
        {
            float t = n == 1 ? 0.5f : (float)i / (n - 1);
            list.Add(new SpawnGroup
            {
                edible = ed[key], count = 1,
                center = new Vector2(Mathf.Lerp(x1, x2, t), Mathf.Lerp(z1, z2, t)),
                radius = 0.05f, ring = false, decorative = false
            });
        }
    }

    private static LevelData MakeLevel(int id, string title, int diff, float time, float map, int tier, float growthMul, float cam,
